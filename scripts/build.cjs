const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const { execFileSync } = require('node:child_process');
const root = path.resolve(__dirname, '..');
const dist = path.join(root, 'dist');
fs.rmSync(dist, { recursive: true, force: true });
fs.mkdirSync(dist, { recursive: true });
execFileSync(process.execPath, ['build-mc.js'], { cwd: path.join(root, 'src'), stdio: 'inherit' });
fs.renameSync(path.join(root, 'src/quiz-mc.html'), path.join(dist, 'quiz-mc.html'));
execFileSync(process.execPath, ['src/build-standalone.js'], { cwd: root, stdio: 'inherit' });
const hash = file => crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex');
const names = ['index.html', 'quiz-mc.html', 'assets/cover/intro-v060.webp', 'assets/cover/intro-v060.jpg', ...fs.readdirSync(path.join(dist, 'assets/avatars')).sort().map(name => 'assets/avatars/' + name)];
if (names.length !== 22) throw Error('Expected exactly 2 HTML files, 2 cover images and 18 avatar derivatives');
const files = names.map(name => ({ path: name, bytes: fs.statSync(path.join(dist, name)).size, sha256: hash(path.join(dist, name)) }));
const commit = process.env.GITHUB_SHA || 'local';
if (commit !== 'local' && !/^[0-9a-f]{40}$/.test(commit)) throw Error('Invalid build commit');
const meta = { schema: 1, commit, dataSha256: hash(path.join(root, 'src/data.js')), files };
fs.writeFileSync(path.join(dist, 'build-meta.json'), JSON.stringify(meta, null, 2) + '\n');
console.log(`Built ${files.length} website files; commit=${commit}`);
